"""Regenerate checked-in brand assets. Requires Python 3, Pillow and rsvg-convert.

Run from any directory; no network access or build-time generation is needed.
The app and player icons get PNGs at every size; 16px rasters come from the
pixel-hinted `*-16.svg` sources. The symbolic icon is SVG-only because its
colour is supplied by the desktop. ICO uses the Windows/Linux tile; ICNS uses
the macOS-grid source (`*-macos.svg`). Tray glyphs (`*-tray-{dark,light}`) are
derived from the app icon's glyph path, see `tray_svg`. See docs/design/brand.md.
"""

import io
from pathlib import Path
import re
import shutil
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "crates/kinema-desktop/assets/brand"
SIZES = (16, 24, 32, 48, 64, 128, 256, 512)
APP_ID = "dev.tlmtech.kinema"
HINTED_SIZE = 16

# Tray glyph: the app icon's white glyph without the tile, one flat colour.
TRAY_COLORS = {"dark": "#232629", "light": "#FFFFFF"}
TRAY_SIZES = (16, 18, 20, 22, 24, 32, 36, 40, 44, 48, 64)
GLYPH_X0, GLYPH_X1 = 266.6, 781.4  # glyph box in the 1024 app grid
GLYPH_Y0, GLYPH_Y1 = 200.0, 824.0
STEM_X1 = 408.9  # right edge of the stem; the arm starts here
LICENSE = (
    "<!-- SPDX-FileCopyrightText: 2026 Thilina Lakshan <thilinalakshanmail@gmail.com> -->\n"
    "<!-- SPDX-License-Identifier: Apache-2.0 -->\n"
)


def render(svg, size):
    return subprocess.check_output(
        ["rsvg-convert", "--width", str(size), "--height", str(size), str(svg)]
    )


def source(name, size):
    hinted = BRAND / f"{name}-{HINTED_SIZE}.svg"
    if size == HINTED_SIZE and hinted.is_file():
        return hinted
    return BRAND / f"{name}.svg"


def image(svg, size):
    with Image.open(io.BytesIO(render(svg, size))) as png:
        return png.convert("RGBA")


def glyph_path():
    text = (BRAND / f"{APP_ID}.svg").read_text()
    return re.search(r'<path fill="#ffffff" d="([^"]+)"', text).group(1)


def number(value):
    return f"{value:.2f}".rstrip("0").rstrip(".")


def map_path(path, fx, fy):
    """Apply per-axis functions to every coordinate (M/L/Q/Z paths only)."""
    out = []
    for command, args in re.findall(r"([MLQZ])([^MLQZ]*)", path):
        values = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", args)]
        coords = [
            number((fx if i % 2 == 0 else fy)(v)) for i, v in enumerate(values)
        ]
        out.append(command + " ".join(coords[i] + " " + coords[i + 1] for i in range(0, len(coords), 2)) if coords else command)
    return "".join(out)


def symbolic_path():
    text = (BRAND / f"{APP_ID}-symbolic.svg").read_text()
    return re.search(r'fill="currentColor" d="([^"]+)"', text).group(1)


def hinted_tray_path(size):
    """Glyph path fitted to a size px grid: whole-pixel height, stem and top/bottom.

    Only the stem is widened to a whole number of pixels; the arm and leg keep
    the logo's proportions, so the silhouette is the app icon's, not a generic K.
    """
    if size == HINTED_SIZE:  # hand-hinted polygon shared with the symbolic icon
        return symbolic_path()
    margin = max(1, round(size / 16))
    height = size - 2 * margin
    unit = height / (GLYPH_Y1 - GLYPH_Y0)
    stem = round((STEM_X1 - GLYPH_X0) * unit)
    width = stem + (GLYPH_X1 - STEM_X1) * unit
    left = int((size - width) // 2)

    def fx(x):
        if x <= STEM_X1:
            return left + (x - GLYPH_X0) * stem / (STEM_X1 - GLYPH_X0)
        return left + stem + (x - STEM_X1) * unit

    return map_path(glyph_path(), fx, lambda y: margin + (y - GLYPH_Y0) * unit)


def tray_svg(variant, size=None):
    """size None: 1024-grid master. size == HINTED_SIZE: the checked-in 16px source."""
    color = TRAY_COLORS[variant]
    if size is None:
        grid = 1024
        unit = 896 / (GLYPH_Y1 - GLYPH_Y0)
        left = (grid - (GLYPH_X1 - GLYPH_X0) * unit) / 2
        path = map_path(
            glyph_path(),
            lambda x: left + (x - GLYPH_X0) * unit,
            lambda y: 64 + (y - GLYPH_Y0) * unit,
        )
        note = "1024 grid; glyph 896px tall (64px margin), no tile."
    else:
        grid = size
        path = hinted_tray_path(size)
        note = f"Pixel-hinted {size}px tray glyph."
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n' + LICENSE
        + f"<!-- Monochrome {variant} tray glyph ({color}), transparent background. {note}\n"
        + "     Generated by packaging/generate-icons.py from the app icon glyph. -->\n"
        + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {grid} {grid}">\n'
        + f'  <path fill="{color}" d="{path}"/>\n</svg>\n'
    )


def write_tray():
    tray = BRAND / "tray"
    tray.mkdir(exist_ok=True)
    for variant in TRAY_COLORS:
        name = f"{APP_ID}-tray-{variant}"
        (BRAND / f"{name}.svg").write_text(tray_svg(variant))
        (BRAND / f"{name}-{HINTED_SIZE}.svg").write_text(tray_svg(variant, HINTED_SIZE))
        for size in TRAY_SIZES:
            svg = tray_svg(variant, size) if size != HINTED_SIZE else None
            source = BRAND / f"{name}-{HINTED_SIZE}.svg"
            if svg is not None:
                source = tray / f".{name}-{size}.svg"
                source.write_text(svg)
            (tray / f"{name}-{size}.png").write_bytes(render(source, size))
            if svg is not None:
                source.unlink()


def main():
    if not shutil.which("rsvg-convert"):
        raise SystemExit("Install librsvg's rsvg-convert first")
    for suffix in ("", "-player"):
        name = APP_ID + suffix
        for size in SIZES:
            output = BRAND / "png" / str(size) / f"{name}.png"
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_bytes(render(source(name, size), size))

    write_tray()

    # Pillow embeds PNG-compressed images in ICO and ICNS; each slot uses the
    # exact-size raster so the hinted 16px artwork is preserved.
    ico_sizes = [size for size in SIZES if size <= 256]
    ico = [image(source(APP_ID, size), size) for size in ico_sizes]
    ico[-1].save(
        BRAND / f"{APP_ID}.ico",
        sizes=[(size, size) for size in ico_sizes],
        append_images=ico[:-1],
    )
    macos = BRAND / f"{APP_ID}-macos.svg"
    icns_sizes = (16, 32, 64, 128, 256, 512, 1024)
    icns = [image(macos, size) for size in icns_sizes]
    icns[-1].save(BRAND / f"{APP_ID}.icns", append_images=icns[:-1])


if __name__ == "__main__":
    main()
