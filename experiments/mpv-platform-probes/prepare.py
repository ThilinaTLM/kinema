#!/usr/bin/env python3
"""Materialize an isolated native probe workspace from the root dependency catalog.

Never downloads ANGLE DLLs, changes driver/environment settings, or edits the
root workspace. Generated output is confined to a marked target directory.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import tomllib
import unittest

HERE = Path(os.path.abspath(__file__)).parent
ROOT = HERE.parents[1]
BUILD = ROOT / "target/mpv-platform-probes"
MARKER = ".kinema-platform-probes-owned"
MARKER_VALUE = "kinema-platform-probes-v1\n"
WINDOWS_FEATURES = [
    "Win32_Graphics_Direct3D", "Win32_Graphics_Direct3D11",
    "Win32_Graphics_Direct3D11on12", "Win32_Graphics_Direct3D12",
    "Win32_Graphics_Dxgi", "Win32_Graphics_Dxgi_Common",
]


def reject_symlinks(path):
    """Check the lexical path, including all existing ancestors, before resolving."""
    for part in [path, *path.parents]:
        if part.is_symlink():
            raise ValueError("refusing symlink in preparation path")


def owned_directory(path):
    reject_symlinks(path)
    if path.exists():
        marker = path / MARKER
        if not path.is_dir() or marker.is_symlink() or not marker.is_file() or marker.read_text() != MARKER_VALUE:
            raise ValueError("refusing unknown preexisting build directory")
    else:
        path.mkdir(parents=True)
        (path / MARKER).write_text(MARKER_VALUE)
    for name in ["Cargo.toml", "Cargo.lock"]:
        candidate = path / name
        reject_symlinks(candidate)
        if candidate.exists() and not candidate.is_file():
            raise ValueError("refusing non-file build output")


def dependency(catalog, name, features=()):
    if name not in catalog:
        raise ValueError(f"missing root workspace.dependencies entry: {name}")
    value = catalog[name]
    entry = {"version": value} if isinstance(value, str) else dict(value)
    entry.pop("path", None)
    if features:
        entry["features"] = sorted(set(entry.get("features", []) + list(features)))
    return "{ " + ", ".join(f"{k} = {json.dumps(v)}" for k, v in entry.items()) + " }"


def manifest(catalog):
    text = '''# Generated by experiments/mpv-platform-probes/prepare.py. Do not hand-edit.
[workspace]
resolver = "3"
members = ["."]

[package]
name = "mpv-platform-probes"
version = "0.1.0"
edition = "2024"
rust-version = "1.97"
publish = false
license = "Apache-2.0"

[lib]
path = "../../experiments/mpv-platform-probes/src/lib.rs"

[[bin]]
name = "mpv-platform-probes"
path = "../../experiments/mpv-platform-probes/src/main.rs"

[target.'cfg(target_os = "windows")'.dependencies]
'''
    text += "windows = " + dependency(catalog, "windows", WINDOWS_FEATURES) + "\n"
    text += "libloading = " + dependency(catalog, "libloading") + "\n"
    text += "\n[target.'cfg(target_os = \"macos\")'.dependencies]\n"
    text += "metal = " + dependency(catalog, "metal") + "\n"
    text += "libloading = " + dependency(catalog, "libloading") + "\n"
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--update-lock", action="store_true", help="intentionally update checked-in experimental lockfile, offline")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        unittest.main(argv=[__file__])
        return
    for path in [HERE, ROOT / "Cargo.toml", HERE / "Cargo.lock", HERE / "src"]:
        reject_symlinks(path)
    for path in (HERE / "src").rglob("*"):
        reject_symlinks(path)
    catalog = tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["dependencies"]
    text = manifest(catalog)
    owned_directory(BUILD)
    (BUILD / "Cargo.toml").write_text(text)
    if args.update_lock:
        subprocess.run(["cargo", "generate-lockfile", "--offline"], cwd=BUILD, check=True)
        shutil.copyfile(BUILD / "Cargo.lock", HERE / "Cargo.lock")
    else:
        shutil.copyfile(HERE / "Cargo.lock", BUILD / "Cargo.lock")
    subprocess.run(["cargo", "metadata", "--no-deps", "--locked", "--offline", "--format-version", "1"],
                   cwd=BUILD, check=True, stdout=subprocess.DEVNULL)
    print("Prepared native texture test-readback workspace (not playback qualification).")


class SafetyTests(unittest.TestCase):
    def test_unknown_directory_is_preserved(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary).resolve() / "unknown"
            path.mkdir()
            sentinel = path / "user-data"
            sentinel.write_text("unchanged")
            with self.assertRaises(ValueError):
                owned_directory(path)
            self.assertEqual(sentinel.read_text(), "unchanged")

    def test_owned_directory_is_reusable(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary).resolve() / "owned"
            owned_directory(path)
            owned_directory(path)
            self.assertEqual((path / MARKER).read_text(), MARKER_VALUE)

    def test_symlink_ancestor_and_output_rejected(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary).resolve()
            real = root / "real"
            real.mkdir()
            link = root / "link"
            try:
                link.symlink_to(real, target_is_directory=True)
            except OSError:
                self.skipTest("host cannot create test symlinks")
            with self.assertRaises(ValueError):
                owned_directory(link / "child")
            owned_directory(real / "owned")
            (real / "owned/Cargo.toml").symlink_to(root / "unrelated")
            with self.assertRaises(ValueError):
                owned_directory(real / "owned")

    def test_catalog_versions_are_not_overridden(self):
        catalog = {"windows": "0.62.2", "metal": "0.29", "libloading": "0.8"}
        text = manifest(catalog)
        for version in catalog.values():
            self.assertIn(f'version = "{version}"', text)
        with self.assertRaises(ValueError):
            manifest({})


if __name__ == "__main__":
    main()
