#!/usr/bin/env python3
"""Generate an isolated real-Kinema GPU app workspace, never a global override."""
import argparse
import copy
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib
import unittest
from unittest import mock

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).resolve().parent
BUILD = ROOT / "target/kinema-gpu-app"
MARKER_VALUE = "kinema-gpu-app-v1\n"
MEMBERS = ("kinema-core", "kinema-mpv", "kinema-desktop")

# Share the audited checksum/copy policy, not the standalone playback producer.
spec = importlib.util.spec_from_file_location(
    "kinema_gpu_preparation", ROOT / "experiments/gpui-mpv-gpu/prepare.py")
policy = importlib.util.module_from_spec(spec)
spec.loader.exec_module(policy)


def scalar(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(scalar(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{scalar(key)} = {scalar(item)}" for key, item in value.items()) + " }"
    raise ValueError(f"unsupported manifest value type: {type(value).__name__}")


def manifest_text(document):
    """Small TOML writer for parsed Cargo manifests; preserves semantic tables."""
    lines = ["# Generated by experiments/kinema-gpu-app/prepare.py; edit root sources instead."]

    def emit(table, path=(), array=False):
        if path:
            heading = ".".join(scalar(part) for part in path)
            lines.extend(["", f"[[{heading}]]" if array else f"[{heading}]"])
        for key, value in table.items():
            if not isinstance(value, dict) and not (isinstance(value, list) and value and all(isinstance(item, dict) for item in value)):
                lines.append(f"{scalar(key)} = {scalar(value)}")
        for key, value in table.items():
            if isinstance(value, dict):
                emit(value, (*path, key))
            elif isinstance(value, list) and value and all(isinstance(item, dict) for item in value):
                for entry in value:
                    emit(entry, (*path, key), array=True)

    emit(document)
    result = "\n".join(lines) + "\n"
    if tomllib.loads(result) != document:
        raise ValueError("generated manifest did not round-trip")
    return result


def write_owned(path, text):
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise ValueError(f"refusing nonregular generated file: {path.name}")
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def absolute_target(entry, source, kind, name):
    entry = copy.deepcopy(entry)
    if "path" not in entry:
        candidates = [source / kind / f"{name}.rs", source / kind / name / "main.rs"]
        if kind == "src/bin":
            candidates += [source / "src/main.rs"]
        existing = [path for path in candidates if path.is_file()]
        if not existing:
            raise ValueError(f"cannot locate source target: {name}")
        entry["path"] = str(existing[0])
    else:
        entry["path"] = str((source / entry["path"]).resolve())
    return entry


def discovered_targets(source, directory):
    location = source / directory
    if not location.is_dir():
        return []
    return [(path.stem, path) for path in sorted(location.glob("*.rs"))] + [
        (path.name, path / "main.rs") for path in sorted(location.iterdir())
        if path.is_dir() and (path / "main.rs").is_file()
    ]


def package_manifest(original, source, windows_gpu=False):
    result = copy.deepcopy(original)
    package = result["package"]
    name = package["name"]
    package["workspace"] = "../.."
    if windows_gpu and name == "kinema-desktop":
        result.setdefault("target", {}).setdefault('cfg(target_os = "windows")', {}).setdefault("dependencies", {})["gpui_windows"] = {"workspace": True, "optional": True}
        features = result.setdefault("features", {}).setdefault("gpu-surface", [])
        if "dep:gpui_windows" not in features:
            features.append("dep:gpui_windows")
    for key in ("readme", "license-file", "build"):
        if isinstance(package.get(key), str):
            package[key] = str((source / package[key]).resolve())
    if "build" not in package and (source / "build.rs").is_file():
        package["build"] = str(source / "build.rs")
    if "lib" in result or (source / "src/lib.rs").is_file():
        result.setdefault("lib", {})["path"] = str((source / result.get("lib", {}).get("path", "src/lib.rs")).resolve())
    package["autolib"] = False
    for kind, directory, auto in [("bin", "src/bin", "autobins"), ("test", "tests", "autotests"),
                                  ("example", "examples", "autoexamples"), ("bench", "benches", "autobenches")]:
        entries = [absolute_target(entry, source, directory, entry.get("name", name))
                   for entry in result.get(kind, [])]
        if package.get(auto, True):
            discovered = discovered_targets(source, directory)
            if kind == "bin" and (source / "src/main.rs").is_file():
                discovered.insert(0, (name, source / "src/main.rs"))
            for target_name, path in discovered:
                if not any(entry.get("name") == target_name or Path(entry["path"]) == path for entry in entries):
                    entries.append({"name": target_name, "path": str(path)})
        if entries:
            result[kind] = entries
        package[auto] = False
    return result


def workspace_manifest(original, patch_crates=None):
    patch_crates = policy.PATCH_CRATES if patch_crates is None else patch_crates
    result = copy.deepcopy(original)
    workspace = result["workspace"]
    workspace["members"] = [f"crates/{name}" for name in MEMBERS]
    workspace["default-members"] = ["crates/kinema-desktop"]
    workspace.pop("exclude", None)
    workspace["resolver"] = "3"
    catalog = workspace["dependencies"]
    for name, value in catalog.items():
        if isinstance(value, dict) and "path" in value:
            if name in MEMBERS:
                value["path"] = f"crates/{name}"
            else:
                value["path"] = str((ROOT / value["path"]).resolve())
    gpu_catalog = ["gpui", "gpui_wgpu", "gpui_apple"]
    if "gpui-pre-windows" in patch_crates.values():
        gpu_catalog.append("gpui_windows")
    for name in gpu_catalog:
        if name not in catalog:
            raise ValueError(f"missing root shared dependency catalog entry: {name}")
        value = catalog[name]
        if isinstance(value, str):
            value = {"version": value}
        if value.get("version") != "=0.3.9":
            raise ValueError(f"expected exact shared GPUI version =0.3.9: {name}")
        features = set(value.get("features", [])) | {"gpu-video-experiment"}
        if name == "gpui_apple":
            features.add("runtime_shaders")
        value["features"] = sorted(features)
        catalog[name] = value
    expected = {name: {"path": f"vendor/{name}"} for name in patch_crates.values()}
    if "replace" in result or ("patch" in result and result["patch"] != {"crates-io": expected}):
        raise ValueError("unreviewed root patches/replacements cannot propagate")
    result["patch"] = {"crates-io": {name: {"path": str(ROOT / "vendor" / name)} for name in patch_crates.values()}}
    return result


def copy_tracked_support(source, destination):
    # Never copy whole source/user directories or ignored/generated files. These
    # support env!(CARGO_MANIFEST_DIR) references in unit/integration tests.
    raw = subprocess.check_output(
        ["git", "ls-files", "-z", "--", "assets", "tests/fixtures", "fixtures"], cwd=source)
    for name in raw.decode().split("\0"):
        if not name:
            continue
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError("unsafe tracked support path")
        original = source / relative
        if original.is_symlink() or not original.is_file():
            raise ValueError("tracked support file missing or symlinked")
        target = destination / relative
        current = destination
        for component in relative.parts[:-1]:
            current /= component
            if current.is_symlink() or (current.exists() and not current.is_dir()):
                raise ValueError("non-directory generated support path")
            current.mkdir(exist_ok=True)
        if target.is_symlink() or (target.exists() and not target.is_file()):
            raise ValueError("nonregular generated support file")
        if not target.exists() or target.read_bytes() != original.read_bytes():
            shutil.copy2(original, target)


def prepare(update_lock=False, manifests_only=False):
    original = tomllib.loads((ROOT / "Cargo.toml").read_text())
    patch_crates = policy.selected_patch_crates(ROOT / "experiments/gpui-mpv-gpu/patches")
    windows_gpu = "gpui-pre-windows" in patch_crates.values()
    if sys.platform == "win32" and not windows_gpu:
        raise ValueError("Windows GPU app requires the fifth GPUI Windows adapter patch")
    workspace = workspace_manifest(original, patch_crates)
    policy.owned_directory(BUILD, MARKER_VALUE)
    crates = BUILD / "crates"
    policy.owned_directory(crates, MARKER_VALUE)
    for name in MEMBERS:
        source = ROOT / "crates" / name
        destination = crates / name
        policy.owned_directory(destination, MARKER_VALUE)
        package = package_manifest(tomllib.loads((source / "Cargo.toml").read_text()), source, windows_gpu)
        if name == "kinema-desktop" and "gpu-surface" not in package.get("features", {}):
            raise ValueError("root desktop gpu-surface feature must land before generating app")
        write_owned(destination / "Cargo.toml", manifest_text(package))
        copy_tracked_support(source, destination)
    write_owned(BUILD / "Cargo.toml", manifest_text(workspace))
    write_owned(BUILD / "rust-toolchain.toml", (ROOT / "rust-toolchain.toml").read_text())
    if manifests_only:
        print("Generated app manifests only; no root metadata or lockfile updated.")
        return
    # Root metadata is always --locked: only the lead updates that lockfile.
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--format-version", "1"], cwd=ROOT))
    policy.prepare_sources(BUILD, metadata, ROOT / "experiments/gpui-mpv-gpu/patches",
                           tomllib.loads((ROOT / "Cargo.lock").read_text())["package"], MARKER_VALUE,
                           expected_patches=patch_crates)
    source_lock = SOURCE / "Cargo.lock"
    generated_lock = BUILD / "Cargo.lock"
    if generated_lock.is_symlink() or (generated_lock.exists() and not generated_lock.is_file()):
        raise ValueError("refusing nonregular generated lockfile")
    if source_lock.exists():
        if source_lock.is_symlink():
            raise ValueError("experimental checked-in lockfile cannot be a symlink")
        write_owned(generated_lock, source_lock.read_text())
    elif update_lock:
        # Preserve the lead's locked upstream versions, including versions no
        # longer selectable by a fresh offline resolution. Only generated files
        # are updated; the root lock is a read-only seed, never a destination.
        write_owned(generated_lock, (ROOT / "Cargo.lock").read_text())
    if update_lock:
        subprocess.run(["cargo", "update", "--workspace", "--offline"], cwd=BUILD, check=True)
        write_owned(source_lock, generated_lock.read_text())
    elif not source_lock.exists():
        raise ValueError("missing experimental app lockfile; run prepare --update-lock intentionally after dependencies settle")
    subprocess.run(["cargo", "metadata", "--locked", "--offline", "--format-version", "1", "--no-deps"],
                   cwd=BUILD, check=True, stdout=subprocess.DEVNULL)
    print("Prepared real Kinema regression workspace using promoted vendor sources; root lockfile and registry unchanged.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--update-lock", action="store_true")
    parser.add_argument("--manifests-only", action="store_true", help="stage manifests while the lead owns root lock/dependency coordination")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        result = unittest.main(argv=[sys.argv[0]], exit=False).result
        if not result.wasSuccessful():
            raise SystemExit(1)
    else:
        if args.update_lock and args.manifests_only:
            parser.error("--update-lock cannot be combined with --manifests-only")
        prepare(args.update_lock, args.manifests_only)


class PreparationTests(unittest.TestCase):
    def test_manifest_round_trip_with_targets_and_platform_dependencies(self):
        document = {"workspace": {"resolver": "3", "dependencies": {"dep": {"version": "1", "features": ["a"]}}},
                    "target": {"cfg(target_os = \"linux\")": {"dependencies": {"dep": {"workspace": True}}}},
                    "bin": [{"name": "main", "path": "/absolute/main.rs"}, {"name": "probe", "required-features": ["probe"]}]}
        self.assertEqual(tomllib.loads(manifest_text(document)), document)

    def test_original_sources_and_all_targets_are_absolute(self):
        with tempfile.TemporaryDirectory() as temporary:
            source = Path(temporary)
            for relative in ("src/main.rs", "src/lib.rs", "src/bin/ui-probe.rs", "tests/check.rs", "tests/nested/main.rs"):
                path = source / relative
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text("// fixture")
            original = {"package": {"name": "fixture", "version": {"workspace": True}},
                        "bin": [{"name": "ui-probe", "path": "src/bin/ui-probe.rs", "required-features": ["ui-probe"]}]}
            generated = package_manifest(original, source)
            self.assertEqual(generated["lib"]["path"], str(source / "src/lib.rs"))
            self.assertEqual({entry["name"] for entry in generated["bin"]}, {"fixture", "ui-probe"})
            self.assertEqual({entry["name"] for entry in generated["test"]}, {"check", "nested"})
            for kind in ("lib",):
                self.assertTrue(Path(generated[kind]["path"]).is_absolute())
            for kind in ("bin", "test"):
                self.assertTrue(all(Path(entry["path"]).is_absolute() for entry in generated[kind]))
            self.assertEqual(original["bin"][0]["path"], "src/bin/ui-probe.rs")
            self.assertEqual(generated["package"]["workspace"], "../..")

    def test_catalog_feature_changes_are_generated_only(self):
        catalog = {name: {"version": "=0.3.9", "package": package} for name, package in
                   [("gpui", "gpui-pre"), ("gpui_wgpu", "gpui-pre-wgpu"), ("gpui_apple", "gpui-pre-apple"), ("gpui_windows", "gpui-pre-windows")]}
        original = {"workspace": {"dependencies": catalog, "members": ["old"]}}
        generated = workspace_manifest(original)
        for name in catalog:
            self.assertNotIn("features", original["workspace"]["dependencies"][name])
            expected = ["gpu-video-experiment", "runtime_shaders"] if name == "gpui_apple" else ["gpu-video-experiment"]
            self.assertEqual(generated["workspace"]["dependencies"][name]["features"], expected)
        self.assertEqual(len(generated["patch"]["crates-io"]), 5)

    def test_promoted_root_patch_paths_are_rebased_and_unknown_patches_rejected(self):
        catalog = {name: {"version": "=0.3.9"} for name in
                   ["gpui", "gpui_wgpu", "gpui_apple", "gpui_windows"]}
        patches = {name: {"path": f"vendor/{name}"} for name in policy.PATCH_CRATES.values()}
        original = {"workspace": {"dependencies": catalog}, "patch": {"crates-io": patches}}
        generated = workspace_manifest(original)
        for name in patches:
            self.assertEqual(generated["patch"]["crates-io"][name]["path"], str(ROOT / "vendor" / name))
            self.assertEqual(original["patch"]["crates-io"][name]["path"], f"vendor/{name}")
        original["patch"]["crates-io"]["unknown"] = {"path": "target/untrusted"}
        with self.assertRaises(ValueError):
            workspace_manifest(original)

    def test_windows_adapter_wiring_is_generated_only(self):
        original = {"package": {"name": "kinema-desktop"}, "features": {"gpu-surface": []}}
        with tempfile.TemporaryDirectory() as temporary:
            generated = package_manifest(original, Path(temporary), windows_gpu=True)
        self.assertEqual(generated["features"]["gpu-surface"], ["dep:gpui_windows"])
        self.assertEqual(generated["target"]['cfg(target_os = "windows")']["dependencies"]["gpui_windows"], {"workspace": True, "optional": True})
        self.assertEqual(original["features"]["gpu-surface"], [])
        catalog = {name: {"version": "=0.3.9"} for name in ["gpui", "gpui_wgpu", "gpui_apple", "gpui_windows"]}
        root = {"workspace": {"dependencies": catalog}}
        five = dict(policy.PATCH_CRATES)
        generated_root = workspace_manifest(root, five)
        self.assertEqual(generated_root["workspace"]["dependencies"]["gpui_windows"]["features"], ["gpu-video-experiment"])
        self.assertEqual(len(generated_root["patch"]["crates-io"]), 5)
        self.assertNotIn("features", root["workspace"]["dependencies"]["gpui_windows"])

    def test_only_tracked_support_is_copied_and_symlinks_fail_closed(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            source, destination = root / "source", root / "generated"
            (source / "assets").mkdir(parents=True)
            destination.mkdir()
            (source / "assets/fixture.txt").write_text("tracked fixture")
            (source / "assets/user-secret.txt").write_text("not tracked; do not copy")
            with mock.patch.object(subprocess, "check_output", return_value=b"assets/fixture.txt\0"):
                copy_tracked_support(source, destination)
                self.assertEqual((destination / "assets/fixture.txt").read_text(), "tracked fixture")
                self.assertFalse((destination / "assets/user-secret.txt").exists())
                (destination / "assets/fixture.txt").unlink()
                (destination / "assets/fixture.txt").symlink_to(source / "assets/user-secret.txt")
                with self.assertRaises(ValueError):
                    copy_tracked_support(source, destination)
                self.assertEqual((source / "assets/user-secret.txt").read_text(), "not tracked; do not copy")

    def test_symlinked_writes_are_rejected_without_touching_target(self):
        with tempfile.TemporaryDirectory() as temporary:
            target = Path(temporary) / "user-file"
            target.write_text("keep")
            link = Path(temporary) / "Cargo.toml"
            link.symlink_to(target)
            with self.assertRaises(ValueError):
                write_owned(link, "replace")
            self.assertEqual(target.read_text(), "keep")

    def test_build_reports_real_executable_not_test_harness(self):
        # Exercise only the artifact parser, never the ordinary run/main branch.
        script = (SOURCE / "run.sh").read_text()
        parser = script.split("<<'PY'\n", 1)[1].split("\nPY\n", 1)[0]
        with tempfile.TemporaryDirectory() as temporary:
            artifacts = Path(temporary) / "artifacts.jsonl"
            artifacts.write_text("\n".join(json.dumps(record) for record in [
                {"reason": "compiler-artifact", "target": {"name": "kinema-desktop"},
                 "profile": {"test": True}, "executable": "/build/deps/test-harness"},
                {"reason": "compiler-artifact", "target": {"name": "kinema-desktop"},
                 "profile": {"test": False}, "executable": "C:/build/kinema-desktop.exe"},
                {"reason": "compiler-message", "message": "do not forward raw JSON"},
            ]))
            result = subprocess.run([sys.executable, "-c", parser, str(artifacts)],
                                    check=True, capture_output=True, text=True)
            self.assertEqual(result.stdout, "Built experimental app: C:/build/kinema-desktop.exe\n")

    def test_build_markers_are_not_interchangeable(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "build"
            policy.owned_directory(path, MARKER_VALUE)
            with self.assertRaises(ValueError):
                policy.owned_directory(path)  # standalone marker must not match


if __name__ == "__main__":
    main()
